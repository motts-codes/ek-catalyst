#!/usr/bin/env python3
"""Build the 10x10 estimator's price table from the client's pricing workbook.

Reads EK_10x10_Pricing_AllPrograms.xlsx (the "Source Pricing (DB)" and "Active 10x10" tabs),
resolves the workbook's own formulas (group-fills such as "=R27", the SUMPRODUCT 10x10 total),
and writes lib/estimator/ten-by-ten-prices.ts: every active program x door style x color the
dropdowns offer, with the 10x10 cabinet price. Per-linear-foot and the GreenSky payment are
worked out at render time from the constants the workbook keeps on the Source tab.

    python3 scripts/build-ten-by-ten-prices.py ~/Downloads/"Kichen estimator"/EK_10x10_Pricing_AllPrograms.xlsx

Re-run whenever EK sends a new workbook; commit the generated file.
"""
import json
import re
import sys
from collections import OrderedDict

import openpyxl

if len(sys.argv) < 2:
    sys.exit(__doc__)

wb = openpyxl.load_workbook(sys.argv[1], data_only=False)
src = wb["Source Pricing (DB)"]
active = wb["Active 10x10"]

APR = float(src["B3"].value)
TERM = int(src["B4"].value)
LINEAR_FEET = float(src["B5"].value)

# BOM quantities (row 7, columns G..R) and the per-row cell values with references resolved.
cols = [c for c in "GHIJKLMNOPQR"]
qty = [float(src[f"{c}7"].value) for c in cols]
ref = re.compile(r"^=([A-R])(\d+)$")


def cell(col, row, depth=0):
    v = src[f"{col}{row}"].value
    if isinstance(v, str) and (m := ref.match(v.strip())):
        if depth > 5:
            raise ValueError(f"reference loop at {col}{row}")
        return cell(m.group(1), int(m.group(2)), depth + 1)
    return float(v) if isinstance(v, (int, float)) else None


def total(row):
    values = [cell(c, row) for c in cols]
    if sum(v is not None for v in values) < 12:
        return None
    return round(sum(q * v for q, v in zip(qty, values) if v is not None), 2)


# The Active tab's price formula points at a Source row: "...'Source Pricing (DB)'!$S$43..."
src_row = re.compile(r"\$S\$(\d+)")

entries = []
for row in active.iter_rows(min_row=5, values_only=True):
    n, program, door, code, color, tier, price_formula, *_rest = row[:7] + (None,) * (7 - len(row[:7]))
    if not program or not door:
        continue
    m = src_row.search(str(price_formula or ""))
    if not m:
        continue
    price = total(int(m.group(1)))
    if price is None:
        print(f"  skip (no price): {program} | {door} | {color}")
        continue
    entries.append(
        OrderedDict(
            program=program.strip(),
            door=door.strip(),
            color=(color or "").strip(),
            tier=(tier or "").strip(),
            code=int(code) if code else None,
            price=price,
        )
    )

print(f"{len(entries)} rows; APR {APR}%, {TERM} months, {LINEAR_FEET} linear feet")
programs = OrderedDict()
for e in entries:
    programs.setdefault(e["program"], set()).add(e["door"])
for p, doors in programs.items():
    print(f"  {p}: {len(doors)} door styles")

out = f"""// GENERATED by scripts/build-ten-by-ten-prices.py from EK_10x10_Pricing_AllPrograms.xlsx.
// Do not edit by hand; re-run the script when EK sends a new workbook.
//
// Every active program x door style x color the 10x10 estimator offers, with the 10x10 cabinet
// price (13 cabinets, about {LINEAR_FEET:g} linear feet, cabinets only). Color never changes the
// price within a door style and tier; shape never changes it at all.

export const TEN_BY_TEN_APR = {APR};
export const TEN_BY_TEN_TERM_MONTHS = {TERM};
export const TEN_BY_TEN_LINEAR_FEET = {LINEAR_FEET:g};

export interface TenByTenRow {{
  program: string;
  door: string;
  color: string;
  tier: string;
  /** The DB class id behind the price. */
  code: number | null;
  /** The 10x10 cabinet price in dollars. */
  price: number;
}}

export const TEN_BY_TEN_ROWS: TenByTenRow[] = {json.dumps(entries, indent=2, ensure_ascii=False)};
"""
path = "lib/estimator/ten-by-ten-prices.ts"
with open(path, "w") as f:
    f.write(out)
print(f"wrote {path}")
